#!/usr/bin/env python3
"""Generates the .cube LUTs shipped with Payday Screen Shaders.

Each look is a pure function of a gamma-space colour, so the LUTs are reproducible and easy to
tune. Run: python3 make_luts.py  (writes into "Payday Screen Shaders/luts/")
"""
import math
import os

SIZE = 33
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "Payday Screen Shaders", "luts")


def clamp(x, lo=0.0, hi=1.0):
    return lo if x < lo else hi if x > hi else x


def luma(r, g, b):
    return 0.299 * r + 0.587 * g + 0.114 * b


def mix(a, b, t):
    return a + (b - a) * t


def smooth(x):
    x = clamp(x)
    return x * x * (3 - 2 * x)


def split_tone(r, g, b, shadow, highlight, amount):
    """Tints shadows towards one colour and highlights towards another, luminance kept."""
    l = luma(r, g, b)
    ws = (1 - smooth(l * 1.6)) * amount
    wh = smooth((l - 0.45) * 1.8) * amount
    r = r + (shadow[0] - 0.5) * ws + (highlight[0] - 0.5) * wh
    g = g + (shadow[1] - 0.5) * ws + (highlight[1] - 0.5) * wh
    b = b + (shadow[2] - 0.5) * ws + (highlight[2] - 0.5) * wh
    nl = luma(r, g, b)
    d = l - nl
    return r + d, g + d, b + d


def saturate_by(r, g, b, s):
    l = luma(r, g, b)
    return mix(l, r, s), mix(l, g, s), mix(l, b, s)


def s_curve(x, strength):
    return mix(x, smooth(x), strength)


def neutral(r, g, b):
    return r, g, b


def ops_room(r, g, b):
    # The modpack's operations-room language: charcoal cool shadows, ivory highlights,
    # colour held back but never grey.
    r, g, b = saturate_by(r, g, b, 0.82)
    r, g, b = split_tone(r, g, b, (0.44, 0.49, 0.56), (0.56, 0.53, 0.46), 0.22)
    r, g, b = (s_curve(r, 0.18), s_curve(g, 0.18), s_curve(b, 0.18))
    return r, g, b


def heist_warm(r, g, b):
    # Warm interiors and sodium light, teal kept to the deepest shadows.
    r, g, b = split_tone(r, g, b, (0.46, 0.51, 0.53), (0.58, 0.52, 0.42), 0.26)
    r, g, b = saturate_by(r, g, b, 1.05)
    r, g, b = (s_curve(r, 0.12), s_curve(g, 0.12), s_curve(b, 0.12))
    return r, g, b


def night_ops(r, g, b):
    # Moonlit exteriors: cool, slightly lifted blacks, desaturated.
    r, g, b = saturate_by(r, g, b, 0.72)
    r, g, b = split_tone(r, g, b, (0.43, 0.48, 0.60), (0.49, 0.51, 0.53), 0.3)
    lift = 0.025
    return r + lift * (1 - r), g + lift * (1 - g), b + lift * 1.4 * (1 - b)


def film_stock(r, g, b):
    # Print-film feel: filmic toe and shoulder, warm mids, gentle crossover.
    def filmic(x):
        x = clamp(x)
        toe = x * x * 0.6 + x * 0.4
        return mix(toe, 1 - (1 - x) ** 2.2, x)

    r, g, b = filmic(r), filmic(g), filmic(b)
    r, g, b = split_tone(r, g, b, (0.47, 0.5, 0.52), (0.55, 0.52, 0.47), 0.18)
    return saturate_by(r, g, b, 0.9)


LOOKS = {
    "1 Neutral": neutral,
    "2 Ops Room": ops_room,
    "3 Heist Warm": heist_warm,
    "4 Night Ops": night_ops,
    "5 Film Stock": film_stock,
}


def write(name, fn):
    path = os.path.join(OUT, name + ".cube")
    with open(path, "w", newline="\n") as f:
        f.write('TITLE "%s"\n' % name[2:])
        f.write("# Generated by dev/nativebuild/make_luts.py\n")
        f.write("LUT_3D_SIZE %d\n" % SIZE)
        for bi in range(SIZE):
            for gi in range(SIZE):
                for ri in range(SIZE):
                    r, g, b = ri / (SIZE - 1), gi / (SIZE - 1), bi / (SIZE - 1)
                    o = fn(r, g, b)
                    f.write("%.6f %.6f %.6f\n" % tuple(clamp(v) for v in o))
    return path


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for name, fn in LOOKS.items():
        print("wrote", write(name, fn))
